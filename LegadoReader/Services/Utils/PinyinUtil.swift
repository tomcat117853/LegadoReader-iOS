        }
        
        if let pinyins = hanziToPinyin[firstChar], let first = pinyins.first {
            return first.uppercased()
        }
        
        let mutableText = NSMutableString(string: text)
        if CFStringTransform(mutableText, nil, kCFStringTransformToLatin, false) {
            let pinyinString = mutableText as String
            if let firstChar = pinyinString.first {
                return String(firstChar).uppercased()
            }
        }
        
        return "#"
    }
    
    static func getPinyinGroup(for text: String) -> String {
        let pinyin = getPinyin(for: text)
        
        if pinyin == "#" {
            if let firstChar = text.first {
                if firstChar >= "0" && firstChar <= "9" {
                    return "0-9"
                }
            }
            return "#"
        }
        
        return pinyin
    }
